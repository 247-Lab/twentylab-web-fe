import { readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
	validateLegacyProductRouteEvidence,
	validateProductEvidenceContract,
} from './legacy-product-route-evidence-lib.mjs';
import { validateLegacyUrlContract } from './legacy-url-inventory-lib.mjs';

const args = process.argv.slice(2);
if (args.length !== 1 || args[0] !== '--write') {
	throw new Error('Usage: node scripts/apply-legacy-product-route-evidence.mjs --write');
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inventoryPath = resolve(root, 'config', 'legacy-url-source-inventory.json');
const evidencePath = resolve(root, 'config', 'legacy-product-route-evidence.json');
const contractPath = resolve(root, 'config', 'legacy-url-contract.json');
const routesPath = resolve(root, 'config', 'legacyProductRoutes.mjs');
const [inventory, evidence, contract] = await Promise.all(
	[inventoryPath, evidencePath, contractPath].map(async (path) => JSON.parse(await readFile(path, 'utf8')))
);

validateLegacyProductRouteEvidence(evidence, inventory);
const classifications = contract.page_classifications
	.filter(({ path }) => !path.startsWith('/product/'))
	.concat(
		evidence.mappings.map(({ path }) => ({
			path,
			disposition: 'preserve',
		}))
	)
	.sort((left, right) => left.path.localeCompare(right.path));
const updatedContract = { ...contract, page_classifications: classifications };
validateLegacyUrlContract(updatedContract, inventory);
validateProductEvidenceContract(evidence, updatedContract);

const routeModule = `// Generated by scripts/apply-legacy-product-route-evidence.mjs.\n// Edit config/legacy-product-route-evidence.json through the capture pipeline instead.\nexport const LEGACY_PRODUCT_ROUTES = Object.freeze(${JSON.stringify(
	evidence.mappings.map(({ path, target_product_id: productId }) => ({ path, productId })),
	null,
	2
)});\n`;

const contractTemporary = `${contractPath}.tmp`;
const routesTemporary = `${routesPath}.tmp`;
await Promise.all([
	writeFile(contractTemporary, `${JSON.stringify(updatedContract, null, 2)}\n`, {
		encoding: 'utf8',
		mode: 0o600,
	}),
	writeFile(routesTemporary, routeModule, { encoding: 'utf8', mode: 0o600 }),
]);
await rename(contractTemporary, contractPath);
await rename(routesTemporary, routesPath);

process.stdout.write(
	`${JSON.stringify({
		applied: true,
		matched_product_count: evidence.matched_product_count,
		unresolved_product_count: evidence.unresolved_product_count,
		classified_page_count: updatedContract.page_classifications.length,
	})}\n`
);
